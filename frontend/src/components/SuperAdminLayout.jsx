function NavItem({ to, label, icon, badge, badgeStyle, onClick }) {
  return (
    <NavLink
      to={to}
      onClick={onClick}
      className={({ isActive }) =>
        `flex items-center gap-2.5 px-4 py-2.5 text-sm border-l-2 transition-all ${
          isActive
            ? "border-indigo-500 bg-white/10 text-white font-medium"
            : "border-transparent text-white/50 hover:text-white/90 hover:bg-white/5"
        }`
      }
    >
      {icon}
      <span className="flex-1">{label}</span>
      {badge && (
        <span className={`text-xs px-1.5 py-0.5 rounded font-medium ${badgeStyle}`}>
          {badge}
        </span>
      )}
    </NavLink>
  );
}

